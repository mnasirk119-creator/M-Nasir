export function generateFonts(inputText: string): FontResult[] {
  if (!inputText) return [];

  const results: FontResult[] = [];

  // Standard Maps
  const mapList = [
    { id: 'bold', name: 'Bold Serif', category: 'Bold' },
    { id: 'italic', name: 'Italic Serif', category: 'Aesthetic' },
    { id: 'boldItalic', name: 'Bold Italic', category: 'Bold' },
    { id: 'script', name: 'Script Cursive', category: 'Aesthetic' },
    { id: 'doubleStruck', name: 'Double Struck', category: 'Special' },
    { id: 'fraktur', name: 'Gothic Fraktur', category: 'Special' },
    { id: 'boldFraktur', name: 'Bold Gothic', category: 'Special' },
    { id: 'monospace', name: 'Retro Monospaced', category: 'Special' },
    { id: 'sansSerif', name: 'Minimal Sans', category: 'Aesthetic' },
    { id: 'gaming', name: 'Pro Gaming', category: 'Gaming' },
    { id: 'tiny', name: 'Small Caps', category: 'Aesthetic' },
    { id: 'bubble', name: 'Bubble Text', category: 'Aesthetic' },
    { id: 'square', name: 'Square Box', category: 'Gaming' },
    { id: 'wide', name: 'Wide Vaporwave', category: 'Aesthetic' },
    { id: 'scary', name: 'Shadow Realm', category: 'Gaming' },
  ];

  mapList.forEach(m => {
    let text = "";
    const map = charMaps[m.id];
    for (const char of inputText) {
      text += map[char] || char;
    }
    results.push({ ...m, text });
  });

  // Functioned Fonts
  results.push({ id: 'inverted', name: 'Upside Down', category: 'Special', text: fontFunctions.inverted(inputText) });
  results.push({ id: 'glitch', name: 'Glitch / Zalgo', category: 'Gaming', text: fontFunctions.glitch(inputText) });
  results.push({ id: 'slash', name: 'Slashed Text', category: 'Special', text: fontFunctions.slash(inputText) });
  results.push({ id: 'strike', name: 'Strike Through', category: 'Special', text: fontFunctions.strike(inputText) });
  results.push({ id: 'underline', name: 'Underlined', category: 'Special', text: fontFunctions.underline(inputText) });
  results.push({ id: 'bridge', name: 'Bridge Arch', category: 'Special', text: fontFunctions.bridge(inputText) });

  // Decorations
  DECORATIONS.forEach((d, index) => {
    results.push({
      id: `deco-${index}`,
      name: `Decorated ${index + 1}`,
      category: 'Decorated',
      text: `${d.prefix}${inputText}${d.suffix}`
    });
  });

  // Add more variations by combining maps and decorations
  const baseStyledText = results[0].text; // Bold
  DECORATIONS.slice(0, 5).forEach((d, index) => {
    results.push({
      id: `combo-${index}`,
      name: `Pro Decorated ${index + 1}`,
      category: 'Gaming',
      text: `${d.prefix}${baseStyledText}${d.suffix}`
    });
  });

  return results;
}
