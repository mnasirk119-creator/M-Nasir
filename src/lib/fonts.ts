const fontFunctions: Record<string, (text: string) => string> = {
  inverted: (text: string) => text.split('').reverse().map(c => charMaps.inverted[c] || c).join(''),
  slash: (text: string) => text.split('').map(c => c === ' ' ? ' ' : c + '\u0338').join(''),
  strike: (text: string) => text.split('').map(c => c === ' ' ? ' ' : c + '\u0336').join(''),
  underline: (text: string) => text.split('').map(c => c === ' ' ? ' ' : c + '\u0332').join(''),
  bridge: (text: string) => text.split('').map(c => c === ' ' ? ' ' : c + '\u0311').join(''),
  glitch: (text: string) => {
    const noise = ["\u0300", "\u0301", "\u0302", "\u0303", "\u0304", "\u0305", "\u0306", "\u0307", "\u0308", "\u0309"];
    return text.split('').map(c => {
      if (c === ' ') return ' ';
      const n = noise[Math.floor(Math.random() * noise.length)];
      return c + n;
    }).join('');
  }
};

